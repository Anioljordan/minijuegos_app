/// Traduce una pista del Impostor teniendo en cuenta la palabra a la que
/// pertenece. Devuelve el texto ya en el idioma pedido cuando hay traducción
/// propia; si no, devuelve la pista en español para que la traduzca el resto
/// del sistema.
String localizeContentHint(String word, String hint, String language) {
  if (language == 'es') return hint;
  final ca = language == 'ca';
  final key = '$word|$hint';
  return (ca ? contentHintContextCa : contentHintContextEn)[key] ??
      (ca ? contentCaExact : contentEnExact)[hint] ??
      hint;
}

/// Traducción directa del contenido, o null si no está en estos mapas.
String? contentExact(String text, String language) {
  if (language == 'es') return text;
  return (language == 'ca' ? contentCaExact : contentEnExact)[text];
}
